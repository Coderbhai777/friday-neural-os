"""
ULTRON Deep Patent & PhD Research Proposal Engine
Generates complete, legally structured patent documents, prior art analyses,
and academic research proposals with auto-PDF compilation.
"""

import os
import io
import re
import sys
import json
import time
from pathlib import Path
from typing import Dict, Any, Optional

DATA_DIR = Path.home() / "Documents" / "ULTRON_Data"
PDF_DIR = Path.home() / "Documents" / "ULTRON_PDFs"
PDF_DIR.mkdir(parents=True, exist_ok=True)


def _get_gemini_model():
    import google.generativeai as genai
    api_key = os.getenv("GEMINI_API_KEY", "")
    if not api_key:
        from dotenv import load_dotenv
        load_dotenv(DATA_DIR / ".env")
        api_key = os.getenv("GEMINI_API_KEY", "")
    genai.configure(api_key=api_key)
    return genai.GenerativeModel("gemini-2.5-flash")


def _export_to_pdf(title: str, content: str, filename_prefix: str = "Patent_Proposal") -> str:
    """Compiles text and markdown into a formatted PDF."""
    try:
        from fpdf import FPDF
        
        pdf = FPDF()
        pdf.set_auto_page_break(auto=True, margin=15)
        pdf.add_page()
        
        # Title
        pdf.set_font("Helvetica", "B", 16)
        clean_title = re.sub(r'[^\x00-\x7F]+', '', title)
        pdf.cell(0, 10, clean_title[:80], ln=True, align="C")
        pdf.ln(5)
        
        # Subtitle / Timestamp
        pdf.set_font("Helvetica", "I", 9)
        pdf.cell(0, 6, f"Generated by ULTRON Neural OS on {time.strftime('%Y-%m-%d %H:%M:%S')}", ln=True, align="C")
        pdf.ln(8)
        
        # Content
        pdf.set_font("Helvetica", "", 10)
        for line in content.split("\n"):
            clean_line = re.sub(r'[^\x00-\x7F]+', '', line)
            if clean_line.startswith("# "):
                pdf.set_font("Helvetica", "B", 13)
                pdf.ln(4)
                pdf.multi_cell(0, 6, clean_line[2:])
                pdf.set_font("Helvetica", "", 10)
            elif clean_line.startswith("## "):
                pdf.set_font("Helvetica", "B", 11)
                pdf.ln(3)
                pdf.multi_cell(0, 5, clean_line[3:])
                pdf.set_font("Helvetica", "", 10)
            elif clean_line.startswith("### "):
                pdf.set_font("Helvetica", "B", 10)
                pdf.ln(2)
                pdf.multi_cell(0, 5, clean_line[4:])
                pdf.set_font("Helvetica", "", 10)
            else:
                pdf.multi_cell(0, 5, clean_line)
                
        safe_name = re.sub(r'[^a-zA-Z0-9_\-]', '_', title)[:30]
        out_path = PDF_DIR / f"{filename_prefix}_{safe_name}_{int(time.time())}.pdf"
        pdf.output(str(out_path))
        return str(out_path)
    except Exception as e:
        # Fallback to saving as markdown
        safe_name = re.sub(r'[^a-zA-Z0-9_\-]', '_', title)[:30]
        out_path = PDF_DIR / f"{filename_prefix}_{safe_name}_{int(time.time())}.md"
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(f"# {title}\n\n{content}")
        return str(out_path)


async def draft_patent_proposal(title_or_idea: str, field: str = "AI / Computer Science", auto_pdf: bool = True) -> str:
    """
    Drafts an official patent application document (Abstract, Claims 1-20, Field of Invention,
    Background, Detailed Description of Preferred Embodiments, and Mermaid flowchart).
    """
    prompt = f"""You are a certified Senior Patent Attorney and Technical IP Drafter.
Draft a COMPLETE, exhaustive, legally rigorous provisional/non-provisional patent application specification for the following invention:

INVENTION CONCEPT / TITLE: {title_or_idea}
TECHNICAL FIELD: {field}

You MUST strictly follow this official USPTO/WIPO specification format:
1. TITLE OF THE INVENTION
2. TECHNICAL FIELD
3. BACKGROUND OF THE INVENTION (Problems in prior art, technical limitations)
4. SUMMARY OF THE INVENTION (Technical solutions, novel mechanisms, advantages)
5. BRIEF DESCRIPTION OF THE DRAWINGS (Include a detailed ASCII/Mermaid flowchart description)
6. DETAILED DESCRIPTION OF PREFERRED EMBODIMENTS (Full step-by-step algorithms, hardware/software interactions, system architecture, mathematical formulations)
7. CLAIMS (Draft at least 15-20 distinct claims including 2-3 Independent Claims and multiple Dependent Claims covering methods, systems, and computer-readable media)
8. ABSTRACT (Under 150 words concise technical disclosure)

Be exhaustive, precise, and highly detailed. Show actual mathematical or algorithmic equations where relevant."""

    try:
        model = _get_gemini_model()
        response = model.generate_content(prompt)
        content = response.text
        
        pdf_note = ""
        if auto_pdf:
            pdf_path = _export_to_pdf(title_or_idea, content, filename_prefix="Patent_Proposal")
            pdf_note = f"\n\n[PDF Export Ready]: {pdf_path}"
            
        return f"[PATENT APPLICATION SPECIFICATION GENERATED]\n\n{content}{pdf_note}"
    except Exception as e:
        return f"Error drafting patent proposal: {e}"


async def search_prior_art(query: str, count: int = 5) -> str:
    """
    Searches for prior art patents and academic publications related to an invention or concept.
    """
    from duckduckgo_search import DDGS
    ddg = DDGS()
    
    search_queries = [
        f"{query} patent USPTO Google Patents",
        f"{query} arxiv research paper"
    ]
    
    results = []
    for q in search_queries:
        try:
            hits = list(ddg.text(q, max_results=count))
            for h in hits:
                results.append({
                    "title": h.get("title", ""),
                    "snippet": h.get("body", ""),
                    "url": h.get("href", "")
                })
        except Exception:
            pass
            
    if not results:
        return f"No direct prior art records found for '{query}'."
        
    # Analyze results with Gemini
    prompt = f"""You are a Patent Analyst. Analyze these search results for prior art against the invention topic '{query}':
{json.dumps(results[:8], indent=2)}

Provide:
1. Prior Art Summary & Closest Existing Solutions
2. Key Differentiation & Novelty Opportunities
3. Patentability Assessment Score (1-10)"""

    try:
        model = _get_gemini_model()
        analysis = model.generate_content(prompt).text
        return f"### Prior Art & Novelty Analysis for '{query}':\n\n{analysis}\n\n### References:\n" + "\n".join([f"- [{r['title']}]({r['url']})" for r in results[:5]])
    except Exception as e:
        return f"Prior art results:\n" + "\n".join([f"- {r['title']}: {r['url']}" for r in results[:5]])


async def draft_phd_proposal(topic: str, methodology: str = "Empirical / Algorithmic", auto_pdf: bool = True) -> str:
    """
    Drafts an academic PhD Dissertation Proposal & Research Plan.
    """
    prompt = f"""You are a Distinguished Professor and Doctoral Advisor.
Draft an exhaustive PhD Dissertation Research Proposal on the topic:

TOPIC: {topic}
METHODOLOGY: {methodology}

Structure:
1. PROPOSED THESIS TITLE
2. ABSTRACT
3. PROBLEM STATEMENT & RESEARCH QUESTIONS (Hypotheses)
4. COMPREHENSIVE LITERATURE REVIEW (Foundational frameworks & current gap)
5. THEORETICAL FRAMEWORK & NOVEL METHODOLOGY
6. PROPOSED ARCHITECTURE & EXPERIMENTAL DESIGN (Datasets, baselines, evaluation metrics)
7. EXPECTED CONTRIBUTIONS & IMPLICATIONS
8. 3-YEAR WORK TIMELINE & MILESTONES (Gantt-style)
9. POTENTIAL RISKS & MITIGATION STRATEGIES
10. KEY ACADEMIC CITATIONS & REFERENCES"""

    try:
        model = _get_gemini_model()
        response = model.generate_content(prompt)
        content = response.text
        
        pdf_note = ""
        if auto_pdf:
            pdf_path = _export_to_pdf(topic, content, filename_prefix="PhD_Proposal")
            pdf_note = f"\n\n[Proposal PDF Compiled]: {pdf_path}"
            
        return f"[PhD RESEARCH PROPOSAL COMPILED]\n\n{content}{pdf_note}"
    except Exception as e:
        return f"Error drafting PhD proposal: {e}"
